// Package main generates banner.go
package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"strings"
	"time"
)

const banner = `// Code generated by kanban/gen. DO NOT EDIT.

package banner

// Version ...
var Version = "%s"

// Copyright ...
var Copyright = "© 2020 - %d FloatTech"

// Banner ...
var Banner = "* OneBot + ZeroBot + Golang\n" +
	"* Version " + Version + " - %s\n" +
	"* Copyright " + Copyright + ". All Rights Reserved.\n" +
	"* Project: https://github.com/FloatTech/ZeroBot-Plugin"
`

const timeformat = `2006-01-02 15:04:05 +0800 CST`

func main() {
	f, err := os.Create("banner/banner.go")
	if err != nil {
		panic(err)
	}
	defer f.Close()
	vartag := bytes.NewBuffer(nil)
	vartagcmd := exec.Command("git", "tag", "--sort=committerdate")
	vartagcmd.Stdout = vartag
	err = vartagcmd.Run()
	if err != nil {
		panic(err)
	}
	tags := strings.Fields(vartag.String())
	var version string
	if len(tags) > 0 {
		version = tags[len(tags)-1]
	} else {
		revision, err := exec.Command("git", "rev-parse", "--short", "HEAD").Output()
		if err != nil {
			panic(err)
		}
		version = "dev-" + strings.TrimSpace(string(revision))
	}
	now := time.Now()
	_, err = fmt.Fprintf(f, banner, version, now.Year(), now.Format(timeformat))
	if err != nil {
		panic(err)
	}
}
